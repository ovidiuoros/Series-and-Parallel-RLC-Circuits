        set(maxN, 'Visible', 'on')
        set(minN, 'Visible', 'on');
    else
        set(Gr1, 'Visible', 'off');
        set(Gr2, 'Visible', 'off');
        set(Slider_N, 'Visible', 'off')
        set(frecventa, 'Visible', 'off');
        set(numeN, 'Visible', 'off');
        set(maxN, 'Visible', 'off')
        set(minN, 'Visible', 'off');
    end
end 

